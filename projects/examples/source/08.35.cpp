#include <print>

//////////////////////////////////////////////////////////////////////////////

#include <boost/asio.hpp>

//////////////////////////////////////////////////////////////////////////////

void test(boost::system::error_code const &)
{
    std::print("test\n");
}

//////////////////////////////////////////////////////////////////////////////

int main()
{
    boost::asio::io_context service;

//  --------------------------------------------------------------------------

    boost::asio::steady_timer timer(service, std::chrono::seconds(5));

//  --------------------------------------------------------------------------

    timer.async_wait(&test);

//  --------------------------------------------------------------------------

    service.run();
}

